function getLevel(id: number): 1 | 2 | 3 | 4 | 5 | 6 {
  if (id <= 12) return 1;
  if (id <= 24) return 2;
  if (id <= 36) return 3;
  if (id <= 48) return 4;
  if (id <= 60) return 5;
  return 6;
}

function getType(id: number): Cell["type"] {
  if (SNAKES[id]) return "snake";
  if (ARROWS[id]) return "arrow";
  if (id === 1 || id === 72) return "special";
  return "normal";
}

